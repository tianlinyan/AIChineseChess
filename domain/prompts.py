def format_legal_moves(legal_moves: list, board: list) -> str:
    """将合法走法列表格式化为紧凑的分组文本（公开接口）。

    按棋子类型分组，每行一种棋子，便于 LLM 阅读和选择。
    列走法超过 8 个时自动换行，保持可读性。

    Args:
        legal_moves: [(fr, fc, tr, tc), ...]
        board: 10×9 棋盘（从 ChineseChessGame.board 获取）

    Returns:
        格式化后的走法列表字符串
    """
    if not legal_moves:
        return "（无合法走法 — 困毙）"

    # 按棋子分组
    groups: dict = {}
    for fr, fc, tr, tc in legal_moves:
        piece = board[fr][fc]
        piece_name = PIECE_SYMBOLS.get(piece, piece)
        from_coord = f"{chr(65 + fc)}{fr + 1}"
        to_coord = f"{chr(65 + tc)}{tr + 1}"

        key = f"{piece_name} ({piece.upper()})"
        if key not in groups:
            groups[key] = []
        groups[key].append(f"{from_coord}→{to_coord}")

    # 排序：车 → 马 → 炮 → 兵/卒 → 相/象 → 仕/士 → 帅/将
    piece_order = ['R', 'N', 'C', 'P', 'B', 'A', 'K']
    ordered_keys = sorted(
        groups.keys(),
        key=lambda k: next(
            (i for i, p in enumerate(piece_order)
             if f"({p})" in k), 99)
    )

    lines = []
    lines.append(f"共 {len(legal_moves)} 种合法走法：")
    lines.append("")

    for key in ordered_keys:
        moves = groups[key]
        # 每 8 个走法换行，保持可读性
        move_strs = []
        for i in range(0, len(moves), 8):
            move_strs.append("  ".join(moves[i:i+8]))
        lines.append(f"**{key}** ({len(moves)}种):")
        for ms in move_strs:
            lines.append(f"  {ms}")

    return "\n".join(lines)


def build_move_prompt(current_player: int, board_str: str, history: str,
                      in_check: bool = False,
                      opponent_in_check: bool = False,
                      move_count: int = 0,
                      last_move_str: str = '',
                      legal_move_count: int = 0,
                      legal_moves_str: str = '',
                      last_move_error: str = '',
                      retry_count: int = 0,
                      vision_mode: bool = False,
                      mcts_suggestions: str = '') -> str:
    """构建走子用户提示词

    Args:
        current_player: 当前玩家 1=红方 2=黑方
        board_str: 棋盘文本表示（vision_mode=True 时忽略）
        history: 移动历史文本
        in_check: 当前是否被将军
        opponent_in_check: 对方是否被我方将军
        move_count: 当前回合数
        last_move_str: 对手上一步走子描述（含吃子/将军标记）
        legal_move_count: 当前合法走法数量
        legal_moves_str: 预格式化的合法走法列表字符串（通过 format_legal_moves() 生成）
        last_move_error: 上一次非法走子的错误描述（用于重试反馈）
        retry_count: 当前重试次数
        vision_mode: 视觉模式——棋盘由图像提供，文本中省略棋盘网格

    Returns:
        完整的用户提示词
    """
    player_display = '红方' if current_player == 1 else '黑方'
    opponent_display = '黑方' if current_player == 1 else '红方'
    player_color = '大写字母' if current_player == 1 else '小写字母'
    player_side = '下半棋盘（行 7~10）' if current_player == 1 else '上半棋盘（行 1~4）'

    # 阶段判断（仅用于标签显示）
    if move_count <= 10:
        phase = '开局'
    elif move_count <= 25:
        phase = '中局'
    else:
        phase = '残局'

    parts = []

    # ═══ 身份与局面概况 ═══
    parts.append(f"## 轮到你了：{player_display}（{player_color}）[{phase}]")
    parts.append(f"对手 {opponent_display} · 第 {move_count} 回合")
    parts.append("")

    # ═══ 紧急状态 ═══
    if in_check:
        parts.append("## ⚠️ 你正在被将军！必须应将！")
        parts.append("只能选择能**解除将军**的走法：躲避将/帅、垫子阻挡、或吃掉攻击子。")
        parts.append("")

    if opponent_in_check and not in_check:
        parts.append("## ✅ 你正在将军对方！寻找杀棋或扩大优势。")
        parts.append("")

    # ═══ 对手上一步 ═══
    if last_move_str:
        parts.append(f"对手上一步：{last_move_str}")
        parts.append("")
        # 对手走子后的威胁分析提示
        parts.append("请分析对手上一步的意图：是单纯出动子力？还是在准备将军/捉子/杀棋？")

    # ═══ 棋盘 ═══
    if vision_mode:
        parts.append("棋盘状态见附带图像。请在图像中定位你的棋子，分析局势。")
        parts.append("")
    else:
        parts.append("## 当前棋盘")
        parts.append(f"（你 = 大写 {player_display}，对手 = 小写 {opponent_display}，`.` = 空位）")
        parts.append("```")
        parts.append(board_str.strip())
        parts.append("```")
        parts.append("")

    # ═══ 引擎参考走法（Hybrid 模式预注入） ═══
    if mcts_suggestions:
        parts.append("---")
        parts.append(mcts_suggestions)
        parts.append("")
        parts.append("*请在分析中简要说明是否采纳引擎推荐及理由。*")
        parts.append("")

    # ═══ 合法走法列表（核心新增） ═══
    if legal_moves_str:
        parts.append("---")
        parts.append("## 📋 你的合法走法")
        parts.append("以下列出了你当前**所有可走的合法走法**。请从中选择最优的一个。")
        parts.append("")
        parts.append(legal_moves_str)
        parts.append("")
        parts.append("**请从以上列表中选择一个走法。** 吃子走法和将军走法通常更优先。")
        parts.append("")

    # ═══ 历史 ═══
    parts.append("## 走子历史")
    parts.append(history if history else "（开局第一步，暂无历史）")
    parts.append("")

    # ═══ 操作指引 ═══
    parts.append("## 📏 输出控制在 600 字以内，力求精炼。")
    if mcts_suggestions:
        parts.append("请参考引擎推荐，简要说明你是否采纳及理由，然后调用 move_piece。")
    elif not vision_mode:
        parts.append("按系统提示词中的四步法分析，从合法走法列表中选择最优走法，然后调用 move_piece 工具。")
    else:
        parts.append("分析图像，从合法走法列表中选择最优走法，然后调用 move_piece 工具。")
    parts.append("move_piece(from=\"Xy\", to=\"Xy\")  列 A~I, 行 1~10")
    parts.append("")

    # ═══ 错误反馈（重试） ═══
    if last_move_error:
        parts.append("---")
        parts.append("## ❌ 上一轮走子被系统拒绝")
        parts.append(f"系统反馈：**{last_move_error}**")
        parts.append("")
        parts.append("请仔细检查并修正：")
        parts.append("- 你选择的走法是否在「合法走法列表」中？")
        parts.append("- 起始位置是否有你的棋子？该棋子是否属于你的阵营？")
        parts.append("- 走法是否符合该棋种的移动规则？（见系统提示词的七种棋子走法）")
        parts.append("- 是否违反了送将、将帅对面、或走子限制？")
        parts.append("- 如果提示'不合法的移动'，请确认坐标对应的走法是否正确")
        parts.append("  （马腿被堵？象眼被塞？炮吃子少炮架？兵未过河横走？）")
        if retry_count > 0:
            parts.append(f"这是第 **{retry_count}** 次重试。请从合法走法列表中选择一个**不同的**走法。")
            parts.append("建议选择吃子走法或将军走法，这些通常价值更高。")
        parts.append("")

    return "\n".join(parts)
