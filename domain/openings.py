# ══════════════════════════════════════════════════════════════════════════════
# 前缀映射表
# ══════════════════════════════════════════════════════════════════════════════

_prefix_map: dict = {}
_built: bool = False
_build_lock = threading.Lock()


def _build_prefix_map():
    """从 OPENING_LINES 构建前缀映射表（线程安全）"""
    global _prefix_map, _built
    if _built:
        return
    with _build_lock:
        if _built:
            return
        _prefix_map.clear()

        for line_name, moves in OPENING_LINES.items():
            for i, move in enumerate(moves):
                prefix = tuple(moves[:i])
                if prefix not in _prefix_map:
                    _prefix_map[prefix] = []
                remaining = len(moves) - i
                _prefix_map[prefix].append((move, float(remaining)))

        _built = True


def get_opening_candidates(move_history: list) -> list:
    """返回开局库所有候选走法及其权重。

    与 get_opening_move() 不同，此函数返回全部候选而非随机抽一个。
    用于人类玩家的参考提示。

    Args:
        move_history: [(fr, fc, tr, tc, ...), ...]

    Returns:
        [(move, weight), ...] 按权重降序排列，无候选时返回空列表
    """
    _build_prefix_map()
    prefix = tuple((m[0], m[1], m[2], m[3]) for m in move_history)
    candidates = _prefix_map.get(prefix, [])
    return sorted(candidates, key=lambda x: -x[1])


def get_opening_names(move_history: list) -> list:
    """返回与当前走子历史匹配的开局名称列表。

    用于在 AI 走出开局库走法后，在日志中显示当前开局名称。

    Args:
        move_history: [(fr, fc, tr, tc, ...), ...] — 已落子的走法（含最新一步）

    Returns:
        [str, ...] 匹配的开局名称列表，无匹配时返回空列表
    """
    _build_prefix_map()
    prefix = tuple((m[0], m[1], m[2], m[3]) for m in move_history)
    names = []
    for line_name, moves in OPENING_LINES.items():
        if len(moves) >= len(prefix):
            line_prefix = tuple(moves[:len(prefix)])
            if line_prefix == prefix:
                names.append(line_name)
    return names


def get_opening_move(move_history: list) -> Optional[Move]:
    """查询开局库，返回加权随机最优走法。

    Args:
        move_history: [(fr, fc, tr, tc, ...), ...]

    Returns:
        (fr, fc, tr, tc) 或 None
    """
    _build_prefix_map()
    prefix = tuple((m[0], m[1], m[2], m[3]) for m in move_history)

    if prefix not in _prefix_map:
        return None

    candidates = _prefix_map[prefix]
    if not candidates:
        return None

    total_weight = sum(w for _, w in candidates)
    r = random.uniform(0, total_weight)
    cumulative = 0.0
    for move, weight in candidates:
        cumulative += weight
        if r <= cumulative:
            return move

    return candidates[-1][0]
